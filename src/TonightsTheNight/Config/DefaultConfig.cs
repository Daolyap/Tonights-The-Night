using TonightsTheNight.Util;

namespace TonightsTheNight.Config
{
    /// <summary>
    /// The shipped defaults layer, written to defaults.json on every version change.
    ///
    /// This file describes what actually works in the current build — settings for unbuilt
    /// features are deliberately absent rather than present and inert, so the config never
    /// promises a knob that does nothing.
    /// </summary>
    public static class DefaultConfig
    {
        public const string Version = "0.3.0";

        public static JsonValue Build()
        {
            JsonValue root = JsonValue.NewObject();
            root.Set("version", JsonValue.Of(Version));
            root.Set("_readme", JsonValue.Of(
                "Do not edit this file - it is overwritten on update. Copy any key you want to " +
                "change into user.json, which is never touched. Comments and trailing commas are allowed."));

            JsonValue menu = JsonValue.NewObject();
            menu.Set("key", JsonValue.Of("F6"));
            menu.Set("reloadKey", JsonValue.Of("F5"));
            root.Set("menu", menu);

            JsonValue logging = JsonValue.NewObject();
            logging.Set("level", JsonValue.Of("Info"));   // Debug | Info | Warn | Error
            root.Set("logging", logging);

            // Budget-first: these are the numbers that decide whether the mod runs or hitches.
            JsonValue engine = JsonValue.NewObject();
            engine.Set("pedsPerTick", JsonValue.Of(12));
            // The script itself ticks every frame; this throttles only recruiting and retasking.
            engine.Set("workIntervalMs", JsonValue.Of(50));
            engine.Set("cullDistance", JsonValue.Of(450));
            engine.Set("maxTrackedPeds", JsonValue.Of(120));
            engine.Set("adaptiveBudget", JsonValue.Of(true));
            engine.Set("targetTickMs", JsonValue.Of(1.5));
            root.Set("engine", engine);

            JsonValue riot = JsonValue.NewObject();
            riot.Set("convertAmbientPeds", JsonValue.Of(true));
            // Roughly half the nearby crowd joins a faction. The other half is left completely
            // alone rather than converted into fleeing bystanders: an untouched ped walking
            // normally reads far better than a converted one running, and a street where
            // everyone flees looks as wrong as one where everyone fights.
            riot.Set("conversionChance", JsonValue.Of(0.55));
            riot.Set("recruitRadius", JsonValue.Of(180));
            riot.Set("groupVehicleOccupants", JsonValue.Of(true));
            riot.Set("restoreWorldOnStop", JsonValue.Of(true));
            // Peds who wounded each other re-engage from vanilla AI memory after one task
            // clear, so keep calming them for a few seconds after a stop.
            riot.Set("pacifySeconds", JsonValue.Of(5));
            riot.Set("spawnFactions", JsonValue.Of(true));
            root.Set("riot", riot);

            // Ped density is a per-frame native, so these are applied every tick while active.
            JsonValue density = JsonValue.NewObject();
            density.Set("enabled", JsonValue.Of(true));
            // A riot consumes its own participants. Without extra crowd the local population
            // is spent in a couple of minutes and the street goes quiet. Needs a gameconfig and
            // Heap Adjuster to be safe at this level - see INSTALL.md.
            density.Set("pedMultiplier", JsonValue.Of(2.5));
            density.Set("vehicleMultiplier", JsonValue.Of(0.8));
            density.Set("scenarioMultiplier", JsonValue.Of(0.4));
            root.Set("density", density);

            JsonValue combat = JsonValue.NewObject();
            combat.Set("alwaysFight", JsonValue.Of(true));
            combat.Set("neverFlee", JsonValue.Of(true));
            combat.Set("canUseCover", JsonValue.Of(true));
            combat.Set("canFightArmedWhenUnarmed", JsonValue.Of(true));
            combat.Set("canUseVehicles", JsonValue.Of(false));
            combat.Set("accuracy", JsonValue.Of(20));        // 0-100
            combat.Set("combatAbility", JsonValue.Of(1));    // 0 poor, 1 average, 2 professional
            combat.Set("seeingRange", JsonValue.Of(60));
            combat.Set("hearingRange", JsonValue.Of(60));
            combat.Set("retaskIntervalMs", JsonValue.Of(6000));
            // Stops gunfire and screams pulling fighters out of combat and into a panic run.
            // Turning this off makes a riot scatter the moment the first shot is fired.
            combat.Set("blockPanicEvents", JsonValue.Of(true));

            // SET_PED_COMBAT_ATTRIBUTES IDs. These are community-documented rather than
            // official and are the most likely thing here to be quietly wrong, so they are
            // tunable: if rioters stand around doing nothing, try other values for alwaysFight
            // (46, 5, 1, 17) and reload with the reload key rather than waiting for a new build.
            JsonValue attributeIds = JsonValue.NewObject();
            attributeIds.Set("alwaysFight", JsonValue.Of(46));
            attributeIds.Set("canUseCover", JsonValue.Of(0));
            attributeIds.Set("canUseVehicles", JsonValue.Of(1));
            attributeIds.Set("canDoDrivebys", JsonValue.Of(2));
            attributeIds.Set("canLeaveVehicle", JsonValue.Of(3));
            attributeIds.Set("canFightArmedWhenUnarmed", JsonValue.Of(5));
            combat.Set("attributeIds", attributeIds);

            root.Set("combat", combat);

            // Weapon presets. "mode" leaves each mode's own loadouts alone and is the default,
            // because a mode author balanced theirs and a preset cannot know that. The others
            // replace the loadout of the factions drawn from the ambient crowd only - a preset
            // answers "what is the mob carrying", not "how is the army equipped".
            JsonValue weapons = JsonValue.NewObject();
            weapons.Set("preset", JsonValue.Of("mode"));   // mode | realistic | armed | military | chaos | custom
            // Used when preset is "custom". Bare names or {"name": ..., "weight": ...}.
            weapons.Set("custom", JsonValue.NewArray());
            weapons.Set("customArmedChance", JsonValue.Of(1.0));
            weapons.Set("customArmour", JsonValue.Of(0));
            weapons.Set("customAmmo", JsonValue.Of(120));
            root.Set("weapons", weapons);

            JsonValue blips = JsonValue.NewObject();
            blips.Set("enabled", JsonValue.Of(true));
            blips.Set("maxBlips", JsonValue.Of(40));
            blips.Set("maxDistance", JsonValue.Of(200));
            blips.Set("scale", JsonValue.Of(0.6));
            blips.Set("showOnlyWhenNear", JsonValue.Of(true));
            root.Set("blips", blips);

            JsonValue player = JsonValue.NewObject();
            player.Set("side", JsonValue.Of("neutral"));       // neutral | <faction id>
            // ignored | disliked | target | mode. Default target: during a riot, being just
            // another person on the street is the point. Set "ignored" to watch undisturbed.
            player.Set("stance", JsonValue.Of("target"));
            root.Set("player", player);

            // Where the riot is. Confining it is both the cheapest performance control and the
            // thing that produces the best scenes - one district in flames beats uniform chaos.
            JsonValue zone = JsonValue.NewObject();
            zone.Set("mode", JsonValue.Of("radius"));     // radius | citywide
            zone.Set("radius", JsonValue.Of(300));
            zone.Set("followPlayer", JsonValue.Of(true));
            zone.Set("showOnMap", JsonValue.Of(true));
            root.Set("zone", zone);

            // Compatibility with other mods. These default to the conservative choice: this
            // mod stays out of systems another mod might own.
            JsonValue compatibility = JsonValue.NewObject();
            compatibility.Set("protectEmergencyServices", JsonValue.Of(true));
            compatibility.Set("protectMissionPeds", JsonValue.Of(true));
            // Off by default and expected to stay off. Police/wanted overhauls (OIV packs,
            // LSPDFR-style mods, 6-star replacements) own the wanted system; riot police are
            // built from relationship groups instead, so the two never collide.
            compatibility.Set("manageWantedSystem", JsonValue.Of(false));
            root.Set("compatibility", compatibility);

            // Feature flags. Every extra is optional AND customisable: a switch plus a block.
            JsonValue features = JsonValue.NewObject();

            JsonValue hotReload = JsonValue.NewObject();
            hotReload.Set("enabled", JsonValue.Of(true));
            hotReload.Set("watchFiles", JsonValue.Of(true));
            hotReload.Set("watchIntervalMs", JsonValue.Of(2000));
            hotReload.Set("restartModeOnReload", JsonValue.Of(false));
            features.Set("hotReload", hotReload);

            JsonValue overlay = JsonValue.NewObject();
            overlay.Set("enabled", JsonValue.Of(false));
            overlay.Set("showPerformance", JsonValue.Of(true));
            overlay.Set("showCounts", JsonValue.Of(true));
            overlay.Set("showFactions", JsonValue.Of(true));
            overlay.Set("x", JsonValue.Of(0.015));
            overlay.Set("y", JsonValue.Of(0.28));
            overlay.Set("scale", JsonValue.Of(0.32));
            features.Set("debugOverlay", overlay);

            JsonValue escalation = JsonValue.NewObject();
            escalation.Set("enabled", JsonValue.Of(true));
            features.Set("escalation", escalation);

            JsonValue ambience = JsonValue.NewObject();
            ambience.Set("enabled", JsonValue.Of(true));
            ambience.Set("setWeather", JsonValue.Of(true));
            ambience.Set("setTime", JsonValue.Of(true));
            ambience.Set("setTimecycle", JsonValue.Of(true));
            features.Set("ambience", ambience);

            JsonValue fires = JsonValue.NewObject();
            fires.Set("enabled", JsonValue.Of(true));
            fires.Set("maxActive", JsonValue.Of(8));
            fires.Set("intervalMs", JsonValue.Of(9000));
            fires.Set("radius", JsonValue.Of(120));
            fires.Set("size", JsonValue.Of(20));
            fires.Set("burnVehicles", JsonValue.Of(true));
            features.Set("fires", fires);

            JsonValue purge = JsonValue.NewObject();
            purge.Set("enabled", JsonValue.Of(true));
            purge.Set("startHour", JsonValue.Of(22));
            purge.Set("durationMinutes", JsonValue.Of(12));
            purge.Set("setClock", JsonValue.Of(true));
            features.Set("purge", purge);

            // Driving behaviour for police and military. The mission type and driving style are
            // community-documented rather than official, so they are tunable without a rebuild.
            JsonValue police = JsonValue.NewObject();
            police.Set("driveThroughCrowds", JsonValue.Of(true));
            police.Set("aggressiveness", JsonValue.Of(1.0));
            police.Set("driverAbility", JsonValue.Of(1.0));
            police.Set("muteSirens", JsonValue.Of(false));
            police.Set("vehicleMission", JsonValue.Of(6));       // 6 = ram
            police.Set("drivingStyle", JsonValue.Of(786603));
            police.Set("cruiseSpeed", JsonValue.Of(45));
            police.Set("targetReachedDistance", JsonValue.Of(5));
            police.Set("straightLineDistance", JsonValue.Of(8));
            features.Set("police", police);

            // Car chases. Provocation-driven: hurt someone and drive away, and their side
            // comes after you in a carload. Never touches the wanted system, so this can run
            // alongside a police or wanted overhaul without either noticing the other.
            JsonValue pursuit = JsonValue.NewObject();
            pursuit.Set("enabled", JsonValue.Of(true));
            // How long after you hurt someone their faction still wants to chase you.
            pursuit.Set("grudgeSeconds", JsonValue.Of(45));
            pursuit.Set("maxChases", JsonValue.Of(2));
            pursuit.Set("crewSize", JsonValue.Of(3));
            // "Tries to drive off" is the trigger, in metres per second. Sitting still in a
            // car should get you dragged out of it, not tailed.
            pursuit.Set("minPlayerSpeed", JsonValue.Of(6));
            pursuit.Set("formRadius", JsonValue.Of(120));
            pursuit.Set("gatherRadius", JsonValue.Of(35));
            pursuit.Set("vehicleSearchRadius", JsonValue.Of(45));
            // How long the crew gets to reach the car on foot before they are warped in. A
            // chase that never leaves the kerb is worse than one that starts a bit too neatly.
            pursuit.Set("boardTimeoutMs", JsonValue.Of(7000));
            pursuit.Set("cooldownMs", JsonValue.Of(12000));
            pursuit.Set("updateIntervalMs", JsonValue.Of(500));
            pursuit.Set("retaskMs", JsonValue.Of(5000));
            pursuit.Set("giveUpDistance", JsonValue.Of(320));
            pursuit.Set("giveUpSeconds", JsonValue.Of(12));
            pursuit.Set("maxSeconds", JsonValue.Of(150));
            pursuit.Set("driveBys", JsonValue.Of(true));
            pursuit.Set("driveByRange", JsonValue.Of(60));
            pursuit.Set("driveByAccuracy", JsonValue.Of(40));
            // Off: they tail you and shoot. On: they drive into you instead.
            pursuit.Set("ram", JsonValue.Of(false));
            pursuit.Set("aggressiveness", JsonValue.Of(1.0));
            pursuit.Set("driverAbility", JsonValue.Of(1.0));
            pursuit.Set("cruiseSpeed", JsonValue.Of(60));
            pursuit.Set("drivingStyle", JsonValue.Of(786603));
            pursuit.Set("blip", JsonValue.Of(true));
            pursuit.Set("notify", JsonValue.Of(true));
            features.Set("pursuit", pursuit);

            // Looting. Gated on the escalation phase, so it starts once the riot has been
            // going a while rather than in the first thirty seconds.
            JsonValue looting = JsonValue.NewObject();
            looting.Set("enabled", JsonValue.Of(true));
            looting.Set("maxActive", JsonValue.Of(6));
            looting.Set("intervalMs", JsonValue.Of(6000));
            looting.Set("radius", JsonValue.Of(90));
            looting.Set("jobSeconds", JsonValue.Of(40));
            looting.Set("runDistance", JsonValue.Of(70));
            looting.Set("carryProps", JsonValue.Of(true));
            // Fighters are busy. Looting is mostly what the people who were never going to
            // fight do instead, which is also what stops it thinning out the riot.
            looting.Set("fighterChance", JsonValue.Of(0.2));
            looting.Set("stealVehicles", JsonValue.Of(true));
            looting.Set("vehicleChance", JsonValue.Of(0.25));
            looting.Set("vehicleSearchRadius", JsonValue.Of(30));
            looting.Set("getawaySpeed", JsonValue.Of(25));
            looting.Set("drivingStyle", JsonValue.Of(786603));
            features.Set("looting", looting);

            JsonValue profiles = JsonValue.NewObject();
            profiles.Set("enabled", JsonValue.Of(true));
            profiles.Set("autoload", JsonValue.Of(""));
            features.Set("profiles", profiles);

            root.Set("features", features);
            return root;
        }
    }
}
